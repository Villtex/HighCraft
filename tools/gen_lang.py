def build():
    out = {}
    for k, v in ITEMS.items(): out[f'item.highcraft.{k}'] = v
    for k, v in BLOCKS.items(): out[f'block.highcraft.{k}'] = v
    for k, v in EFFECTS.items(): out[f'effect.highcraft.{k}'] = v
    for k, v in TOOLTIPS.items(): out[f'tooltip.highcraft.{k}'] = v
    for k, v in LANG.items(): out[k] = v
    for k, (title, desc) in ADV.items():
        out[f'advancements.highcraft.{k}.title'] = title
        out[f'advancements.highcraft.{k}.description'] = desc
    # escape single percent signs (Minecraft format strings)
    for k in out:
        out[k] = re.sub(r'%(?!s|%|\d\$s)', '%%', out[k]).replace('%%%', '%%')
    return out

